function slugify($name)
{
    $noParen = preg_replace('/\s*\(.*?\)\s*/', '', $name);
    $lower = strtolower($noParen);
    $slug  = preg_replace('/[^a-z0-9]+/', '_', $lower);
    return trim($slug, '_');
}
